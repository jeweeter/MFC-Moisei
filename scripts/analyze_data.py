#!/usr/bin/env python3
"""Анализ исходной базы знаний -> docs/DATA_ANALYSIS.md.

Отчёт генерируется из данных, а не пишется руками: при обновлении выгрузки
с mfc71.ru достаточно перезапустить скрипт, и все цифры в документе обновятся.

Запуск:  python scripts/analyze_data.py
"""
from __future__ import annotations

import collections
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.config import get_settings  # noqa: E402
from app.index_store import get_store  # noqa: E402
from app.ingest.schema import SECTIONS, UNUSED_FIELDS  # noqa: E402

RE_LEGAL = re.compile(
    r"регламент|постановлени|приказ[а-я]*\s|федеральн[а-я]+\s+закон|№\s?\d+-ФЗ|"
    r"кодекс[а-я]*\s|распоряжени", re.I,
)
TEXT_FIELDS = [s.key for s in SECTIONS if s.code != "title"]


def pct(part: int, total: int) -> str:
    return f"{part / total * 100:.1f}%" if total else "—"


def main() -> None:
    s = get_settings()
    db = json.loads(s.knowledge_file.read_text(encoding="utf-8"))
    store = get_store()
    q = dict(store.quality)
    q["noiseRemovedPct"] = round(
        100 - q["clean_bytes"] / max(1, q["raw_bytes"]) * 100, 1
    )
    total = len(db)

    # --- идентификаторы ---
    id_shapes: collections.Counter[str] = collections.Counter()
    non_numeric: list[str] = []
    for row in db:
        sid = str(row["id"])
        if sid.isdigit():
            id_shapes[f"{len(sid)}-значное число"] += 1
        else:
            id_shapes["нечисловой"] += 1
            non_numeric.append(sid)

    # --- НПА ---
    with_legal = sum(
        1 for row in db
        if any(RE_LEGAL.search(row.get(f) or "") for f in TEXT_FIELDS)
    )
    with_acts_files = sum(1 for row in db if row.get("legalActsFiles"))

    # --- названия ---
    titles = [row.get("serviceTitleText") or "" for row in db]
    long_titles = sum(1 for t in titles if len(t) > 200)
    lower_titles = [t for t in titles if t[:1].islower()]

    # --- дубли текста ---
    doc_counter = collections.Counter(
        (row.get("documentsText") or "").strip() for row in db
        if (row.get("documentsText") or "").strip()
    )
    dup_docs = sum(v - 1 for v in doc_counter.values() if v > 1)

    # --- жизненные ситуации ---
    ls_counts = {ls["name"]: ls["count"] for ls in store.life_situations}
    empty_ls = [name for name, c in ls_counts.items() if c == 0]

    # --- пробелы в контенте (из оценочного набора) ---
    gaps = json.loads(
        (ROOT / "backend" / "tests" / "eval_queries.json").read_text(encoding="utf-8")
    ).get("known_gaps", [])

    lines: list[str] = []
    add = lines.append

    add("# Анализ базы знаний и предложения по её доработке")
    add("")
    add("> Документ сгенерирован автоматически: `python scripts/analyze_data.py`.")
    add("> Все цифры посчитаны по фактической выгрузке "
        "`data/raw/db_knowledge.json` и `data/raw/flat_classification.json`.")
    add("")
    add("Это ответ на пункт 3 технического задания: «проанализировать имеющуюся "
        "информацию и сформировать предложения по её дополнению, изменению, "
        "реструктуризации».")
    add("")

    # ---------------------------------------------------------------- 1
    add("## 1. Что в выгрузке есть")
    add("")
    add("| Показатель | Значение |")
    add("|---|---|")
    add(f"| Услуг | **{total}** |")
    add(f"| Ведомств (справочник `by_department`) | {len(store.classification('by_department'))} |")
    add(f"| Отделений МФЦ (`by_branch`) | {len(store.classification('by_branch'))} |")
    add(f"| Жизненных ситуаций (`by_life_situation`) | {len(store.classification('by_life_situation'))} |")
    add(f"| Категорий заявителей (`by_recipient`) | {len(store.classification('by_recipient'))} |")
    add(f"| Объём содержательных полей | {q['raw_bytes'] / 1e6:.2f} МБ HTML → "
        f"{q['clean_bytes'] / 1e6:.2f} МБ текста |")
    add(f"| Доля разметки и служебного мусора | **{q['noiseRemovedPct']}%** |")
    add("")

    # ---------------------------------------------------------------- 2
    add("## 2. Качество HTML в текстовых полях")
    add("")
    add("Поля заполнялись через визуальный редактор копированием из MS Word. "
        "В результате в них лежит не текст, а разметка Word:")
    add("")
    add("* инлайн-стили на каждом `<span>`/`<p>` — до 90% объёма поля;")
    add("* служебные namespace-теги Word: `<o:p>`, `<w:WordDocument>`, `<m:oMath>`, `<xml>`;")
    add("* условные комментарии `<!--[if gte mso 9]>` с CSS внутри;")
    add(f"* **{q['images_dropped']}** изображений, вшитых в текст как base64 "
        "(одно поле услуги «Подтверждение личности для приложения \"Госключ\"» "
        "весит 862 КБ, из которых полезного текста — 146 символов);")
    add("* html-сущности `&nbsp;`, `&quot;`, местами экранированные дважды.")
    add("")
    add("**Следствие.** Наивный `strip_tags` даёт нечитаемое месиво, а поиск по сырому "
        "полю ищет по слову `border-box`, а не по тексту регламента. "
        "В проекте это решено конвейером `backend/app/ingest/html_clean.py`, который "
        "восстанавливает структуру (абзацы, списки, нумерацию, таблицы, ссылки) и "
        f"убирает {q['noiseRemovedPct']}% объёма.")
    add("")
    add("**Предложение 1 (изменение).** Хранить в базе знаний размеченный текст в "
        "структурированном виде (Markdown или ограниченный набор тегов `p/ul/ol/li/b/a`) "
        "и запретить вставку из Word без очистки. Это снимает необходимость в очистке "
        "на каждой стороне-потребителе и убирает риск потери смысла при разборе.")
    add("")

    # ---------------------------------------------------------------- 3
    add("## 3. Заполненность разделов")
    add("")
    add("| Раздел | Поле JSON | Заполнено | Пусто | С HTML-разметкой |")
    add("|---|---|---|---|---|")
    for spec in SECTIONS:
        if spec.code == "title":
            continue
        empty = q["empty_sections"].get(spec.code, 0)
        add(f"| {spec.label} | `{spec.key}` | {pct(total - empty, total)} | "
            f"{empty} | {q['html_sections'].get(spec.code, 0)} |")
    add("")
    comp = collections.Counter()
    for svc in store.services.values():
        c = svc["completeness"]
        comp["полные (≥85%)" if c >= 0.85 else
             "частичные (50–85%)" if c >= 0.5 else "неполные (<50%)"] += 1
    add("Полнота карточек: " + ", ".join(f"**{v}** {k}" for k, v in comp.items()) + ".")
    add("")
    add("**Предложение 2 (дополнение).** Ввести обязательный минимум полей для "
        "публикации услуги: документы, срок, стоимость, результат, основания для "
        "отказа. Карточку без этого минимума не выгружать в справочную систему — "
        "оператор всё равно не сможет ей воспользоваться, а поиск будет предлагать "
        "заведомо бесполезный результат. В приложении такие услуги помечены "
        "меткой «неполные данные» и понижены в ранжировании.")
    add("")

    # ---------------------------------------------------------------- 4
    add("## 4. Неиспользуемые и мёртвые поля")
    add("")
    add("| Поле | Заполнено записей | Комментарий |")
    add("|---|---|---|")
    for field in UNUSED_FIELDS:
        filled = sum(1 for row in db if row.get(field))
        note = {
            "descriptionText": "пусто во всех записях",
            "applicantCategories": "дублирует `serviceRecipients`, практически не заполнено",
            "documentsFiles": "приложенные файлы не выгружаются",
            "otherDocuments": "иные документы не выгружаются",
            "legalActsFiles": "бланки заявлений — ключевая для окна вещь, но почти пусто",
        }.get(field, "")
        add(f"| `{field}` | {filled} из {total} | {note} |")
    add("")
    add("**Предложение 3 (реструктуризация).** Мёртвые поля из выгрузки убрать, "
        "а вместо `documentsFiles`/`legalActsFiles` отдавать реальные ссылки на "
        "бланки: оператору в окне нужен не признак «файл есть», а сам бланк.")
    add("")

    # ---------------------------------------------------------------- 5
    add("## 5. Административные регламенты — главный пробел")
    add("")
    add("ТЗ прямо указывает: «Важным моментом является наличие по каждой услуге "
        "административного регламента… утверждённого каким-либо нормативным документом». "
        "В выгрузке отдельного поля под НПА нет вообще.")
    add("")
    add(f"* Упоминание регламента/закона/постановления хотя бы в одном текстовом поле: "
        f"**{with_legal}** из {total} ({pct(with_legal, total)}).")
    add(f"* Поле `legalActsFiles` заполнено у **{with_acts_files}** услуг "
        f"({pct(with_acts_files, total)}).")
    add(f"* То есть у **{total - with_legal}** услуг ({pct(total - with_legal, total)}) "
        "оператор не может сослаться на основание вообще.")
    add("")
    add("**Предложение 4 (дополнение, приоритет №1).** Добавить в схему услуги "
        "отдельный структурированный блок:")
    add("")
    add("```jsonc")
    add("\"legalBasis\": [")
    add("  {")
    add("    \"type\": \"regulation\",              // регламент | закон | постановление | приказ")
    add("    \"title\": \"Административный регламент предоставления…\",")
    add("    \"actNumber\": \"№ 1234\",")
    add("    \"approvedBy\": \"Приказ МВД России\",")
    add("    \"date\": \"2024-03-15\",")
    add("    \"url\": \"http://publication.pravo.gov.ru/…\",")
    add("    \"validFrom\": \"2024-04-01\",")
    add("    \"validTo\": null                     // для отслеживания устаревания")
    add("  }")
    add("]")
    add("```")
    add("")
    add("Это даёт три вещи сразу: ассистент цитирует не «базу знаний», а конкретный "
        "пункт конкретного НПА; появляется машинная проверка устаревания "
        "(`validTo` в прошлом → карточку на ревизию); и становится возможной сверка "
        "со справочной правовой системой по номеру акта, а не по названию услуги.")
    add("")

    # ---------------------------------------------------------------- 6
    add("## 6. Идентификаторы: три несовместимых пространства имён")
    add("")
    add("### 6.1. Формат `db_knowledge.id`")
    add("")
    add("| Формат | Записей |")
    add("|---|---|")
    for shape, cnt in id_shapes.most_common():
        add(f"| {shape} | {cnt} |")
    add("")
    add("Примеры нечисловых id: " + ", ".join(f"`{i}`" for i in non_numeric[:12]) + " — "
        "видно, что часть услуг заводилась вручную и по разным соглашениям "
        "(`vbd_2`, `svo_10`, `CREDIT`, `Srv00054`, `Zabota_Aleksin_1`).")
    add("")
    add("### 6.2. Разрыв связи между файлами")
    add("")
    add("В `flat_classification` у каждой категории есть массив `ids` — по замыслу "
        "это обратный индекс «ведомство → услуги». Фактически:")
    add("")
    add("* в `ids` лежат UUID (`c3116b96-d854-…`);")
    add("* в `db_knowledge.id` лежат числа и строковые коды;")
    add("* **пересечение этих множеств — ноль элементов.**")
    add("")
    add("Обратный индекс из справочника нерабочий. Связи в приложении восстановлены "
        "только по прямым полям услуги (`departmentId`, `mfcIds`, `lifeSituationIds`, "
        "`recipientIds`) — они как раз согласованы:")
    add("")
    add(f"* `departmentId` не находится в справочнике у **{len(q['unknown_department_ids'])}** "
        f"значений, у **{q['missing_department']}** услуг ведомство не указано вовсе;")
    add(f"* `mfcIds` содержит **{len(q['unknown_branch_ids'])}** идентификаторов отделений, "
        "которых нет в справочнике `by_branch`.")
    add("")
    add("**Предложение 5 (реструктуризация).** Привести идентификаторы к одному "
        "пространству имён (UUID) и оставить связь в одну сторону — от услуги к "
        "справочникам. Дублирующий массив `ids` в справочниках убрать: он весит "
        "4 МБ из 4.4 МБ файла классификаторов и при этом не работает.")
    add("")

    # ---------------------------------------------------------------- 7
    add("## 7. Муниципальные дубли: 59% каталога — копии")
    add("")
    add(f"Одна и та же муниципальная услуга заведена отдельной записью для каждого "
        f"муниципального образования. Обнаружено **{q['variant_groups']} групп**, "
        f"в которые входит **{q['variant_services']} услуг** — "
        f"{pct(q['variant_services'], total)} каталога.")
    add("")
    add("| Услуга | Копий |")
    add("|---|---|")
    for g in q["largest_variant_groups"][:10]:
        add(f"| {g['title'][:95]} | {g['count']} |")
    add("")
    add(f"Фактический размер каталога — не {total} услуг, а примерно "
        f"**{total - q['variant_services'] + q['variant_groups']}** различных услуг.")
    add("")
    add(f"Дополнительно: у {len(doc_counter)} услуг перечень документов уникален, "
        f"но **{dup_docs}** записей имеют полностью совпадающий `documentsText` "
        "с другой услугой.")
    add("")
    add("**Предложение 6 (реструктуризация).** Разделить сущности «услуга» и "
        "«вариант предоставления»:")
    add("")
    add("```jsonc")
    add("{")
    add("  \"id\": \"uuid-услуги\",")
    add("  \"title\": \"Выдача градостроительного плана земельного участка\",")
    add("  \"shortTitle\": \"ГПЗУ\",")
    add("  \"documentsText\": \"…общая часть…\",")
    add("  \"variants\": [")
    add("    { \"municipality\": \"Тула\", \"departmentId\": \"…\", \"overrides\": {} },")
    add("    { \"municipality\": \"Алексин\", \"departmentId\": \"…\",")
    add("      \"overrides\": { \"timeTermText\": \"…\" } }")
    add("  ]")
    add("}")
    add("```")
    add("")
    add("Эффект: каталог сокращается вдвое, правка регламента вносится один раз, "
        "а поисковая выдача перестаёт состоять из 26 одинаковых строк. "
        "В приложении это реализовано на лету (группировка по названию), но "
        "правильное место для такой модели — сама база знаний.")
    add("")

    # ---------------------------------------------------------------- 8
    add("## 8. Названия услуг")
    add("")
    add(f"* Средняя длина названия — **{sum(len(t) for t in titles) // total} символов**, "
        f"максимум — **{max(len(t) for t in titles)}**.")
    add(f"* Длиннее 200 символов — **{long_titles}** названий "
        f"({pct(long_titles, total)}).")
    add("* Короткого «человеческого» имени в схеме нет вообще.")
    if lower_titles:
        add(f"* Нарушения единообразия: {len(lower_titles)} назв. со строчной буквы, "
            f"например «{lower_titles[0]}» — аббревиатура ГСП без расшифровки, "
            "в нижнем регистре, не по шаблону остальных.")
    add("")
    add("Отдельная сложность: пары услуг различаются **только хвостом** названия — "
        "«…удостоверяющих личность гражданина Российской Федерации **на территории** "
        "Российской Федерации» и «…**за пределами территории** Российской Федерации». "
        "Обрезание слева делает их неразличимыми в списке.")
    add("")
    add("**Предложение 7 (дополнение).** Добавить поля `shortTitle` (до 80 символов, "
        "для интерфейсов) и `aliases` (народные названия: «загранник», «прописка», "
        "«детские»). Сейчас короткое имя приложение строит эвристикой "
        "(`backend/app/ingest/build_index.py: short_title`), а синонимы ведёт "
        "в собственном словаре `data/dictionaries/synonyms.json` — это работа, "
        "которую логично делать один раз на стороне базы знаний.")
    add("")

    # ---------------------------------------------------------------- 9
    add("## 9. Жизненные ситуации: заполнены у половины каталога")
    add("")
    add(f"Поле `lifeSituationIds` пусто у **{q['no_life_situation']}** услуг из {total} "
        f"({pct(q['no_life_situation'], total)}).")
    add("")
    add("| Жизненная ситуация | Услуг |")
    add("|---|---|")
    for ls in store.life_situations:
        add(f"| {ls['name']} | {ls['count']} |")
    add("")
    if empty_ls:
        add("Ситуации без единой услуги: " + ", ".join(f"«{n}»" for n in empty_ls) + ".")
        add("")
    add("Проверка на осмысленность привязок выявила спорные случаи: например, "
        "«Государственная регистрация самоходных машин и других видов техники» "
        "отнесена к ситуации «Открытие своего дела».")
    add("")
    add("**Предложение 8 (дополнение).** Проставить жизненные ситуации всем услугам "
        "и разрешить множественную привязку с указанием роли "
        "(`primary` — ядро ситуации, `related` — сопутствующая). Без этого «Мастер "
        "по жизненной ситуации» вынужден догадываться: в приложении жизненная "
        "ситуация используется как усиливающий фактор ранжирования, а не как фильтр, "
        "иначе теряется половина базы.")
    add("")

    # --------------------------------------------------------------- 10
    add("## 10. Содержательные пробелы")
    add("")
    add("Проверка типовыми запросами оператора показала, что часть базовых услуг "
        "в выгрузке отсутствует, хотя соответствующие жизненные ситуации заведены:")
    add("")
    for g in gaps:
        add(f"* **«{g['q']}»** — {g['note']}")
    add("")
    add("**Предложение 9 (дополнение).** Сверить каталог с перечнем услуг, "
        "фактически оказываемых в окне: расхождение «жизненная ситуация есть — "
        "услуги нет» должно быть блокирующей ошибкой выгрузки.")
    add("")

    # --------------------------------------------------------------- 11
    add("## 11. Сводка предложений")
    add("")
    add("| № | Тип | Предложение | Эффект |")
    add("|---|---|---|---|")
    add("| 1 | изменение | Хранить текст без Word-разметки (Markdown / белый список тегов) | −54% объёма, устойчивый разбор |")
    add("| 2 | дополнение | Обязательный минимум полей для публикации услуги | нет заведомо бесполезных карточек |")
    add("| 3 | реструктуризация | Убрать мёртвые поля, отдавать реальные бланки | оператор получает бланк, а не признак |")
    add("| 4 | **дополнение** | **Блок `legalBasis` c реквизитами НПА** | **ссылка на основание + контроль устаревания** |")
    add("| 5 | реструктуризация | Единое пространство идентификаторов, убрать нерабочий `ids` | −4 МБ, связи чинятся |")
    add("| 6 | реструктуризация | Модель «услуга + варианты по МО» | каталог вдвое меньше, правка в одном месте |")
