def build_context(fragments: list[dict]) -> str:
    """Собирает блок <КОНТЕКСТ> с пронумерованными фрагментами."""
    parts: list[str] = []
    for i, f in enumerate(fragments, start=1):
        parts.append(
            f"[{i}] Услуга: {f['serviceTitle']}\n"
            f"    Ведомство: {f.get('department') or 'не указано'}\n"
            f"    Раздел: {f['sectionLabel']}\n"
            f"    Текст: {f['text']}"
        )
    return "\n\n".join(parts)


def build_user_message(question: str, fragments: list[dict], service_title: str | None) -> str:
    scope = (f"Оператор смотрит карточку услуги: «{service_title}».\n"
             if service_title else "")
    return (
        f"{scope}Вопрос оператора: {question}\n\n"
        f"<КОНТЕКСТ>\n{build_context(fragments)}\n</КОНТЕКСТ>\n\n"
        "Ответь по правилам, со ссылками [n] на фрагменты."
    )
